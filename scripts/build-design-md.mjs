// Rebuilds the generated token section of DESIGN.md from /tokens.
// Everything between the two markers is replaced; everything else in DESIGN.md is hand-written and kept.
// `npm run check` fails if the committed DESIGN.md differs from what this produces.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = p => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const START = '<!-- tokens:start -->';
const END = '<!-- tokens:end -->';

const color = read('tokens/primitives/color.tokens.json').color;
const resolve = v => {
  if (typeof v !== 'string' || !v.startsWith('{')) return { hex: v, ref: '' };
  const path = v.slice(1, -1).split('.').slice(1);
  let node = color;
  for (const k of path) node = node[k];
  return { hex: node.$value, ref: path.join('/') };
};
const flatten = (obj, prefix = []) =>
  Object.entries(obj).flatMap(([k, v]) => (v && typeof v === 'object' && '$value' in v ? [[[...prefix, k].join('.'), v.$value]] : flatten(v, [...prefix, k])));

const light = Object.fromEntries(flatten(read('tokens/semantic/light.tokens.json').palette));
const dark = Object.fromEntries(flatten(read('tokens/semantic/dark.tokens.json').palette));
const cell = v => { const r = resolve(v); return r.ref ? `\`${r.hex}\` ${r.ref}` : `\`${r.hex}\``; };

const palette = [
  '| Role | Light | Dark |',
  '|---|---|---|',
  ...Object.keys(light).map(k => `| \`${k}\` | ${cell(light[k])} | ${cell(dark[k])} |`),
];

const base = {
  shape: read('tokens/base/shape.tokens.json').shape,
  spacing: read('tokens/base/spacing.tokens.json').spacing,
  typography: read('tokens/base/typography.tokens.json').typography,
};
const unit = base.spacing.unit.$value.value;
const steps = [0.5, 1, 1.5, 2, 3, 4, 5, 6, 8, 10, 12];
const spacing = ['| Step | Pixels |', '|---|---|', ...steps.map(s => `| ${s} | ${s * unit}px |`)];

const weightName = { 300: 'Light', 400: 'Regular', 500: 'Medium', 600: 'Semi Bold', 700: 'Bold' };
const type = [
  '| Text variant | Size | Weight | Line height | Letter spacing |',
  '|---|---|---|---|---|',
  ...Object.entries(base.typography.variant).map(([name, t]) => {
    const v = t.$value;
    const px = Math.round(v.fontSize.value * 16 * 10) / 10;
    const upper = t.$extensions?.['com.northwind']?.textTransform === 'uppercase' ? ', uppercase' : '';
    return `| \`${name}\` | ${px}px | ${weightName[v.fontWeight] ?? v.fontWeight} | ${v.lineHeight} | ${v.letterSpacing.value}em${upper} |`;
  }),
];

const section = [
  START,
  '<!-- Generated by scripts/build-design-md.mjs from /tokens. Do not edit by hand: run `npm run design-md:build`. -->',
  '',
  '### Colour roles',
  '',
  'Use these through component props (`color="secondary"` on Text, `status="error"` on StatusLabel), never as raw values.',
  '',
  ...palette,
  '',
  '### Spacing',
  '',
  `Stack \`gap\` and \`padding\` take these steps. 1 step = ${unit}px. Same as Figma's \`spacing\` variables.`,
  '',
  ...spacing,
  '',
  '### Shape',
  '',
  `Corner radius: ${base.shape.borderRadius.$value.value}px (MUI's single \`shape.borderRadius\`). Status labels are pills.`,
  '',
  '### Text styles',
  '',
  `Font: ${base.typography.fontFamily.$value[0]}. Use these through \`<Text variant>\`. Same names as Figma's \`typography/*\` text styles.`,
  '',
  ...type,
  END,
].join('\n');

const path = new URL('DESIGN.md', root);
const md = readFileSync(path, 'utf8');
const a = md.indexOf(START), b = md.indexOf(END);
if (a < 0 || b < 0) throw new Error('DESIGN.md is missing the tokens:start / tokens:end markers.');
writeFileSync(path, md.slice(0, a) + section + md.slice(b + END.length));
console.log('DESIGN.md token section rebuilt.');
